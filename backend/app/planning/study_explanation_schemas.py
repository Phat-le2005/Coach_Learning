from __future__ import annotations

from datetime import datetime
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from app.planning.study_models import StudyTaskType


class StudyPlanExplanationItem(BaseModel):
    """Summarized view of an individual task for study plan explanation."""

    id: UUID
    title: str = Field(..., description="Display title of the task (e.g. ProblemType name or generic task).")
    task_type: StudyTaskType
    priority: int = Field(..., gt=0)
    estimated_duration_minutes: int = Field(..., gt=0)
    reason_code: str
    problem_type_id: UUID | None = None
    problem_type_name: str | None = None
    concept_id: UUID | None = None
    concept_name: str | None = None


class StudyPlanExplanationInput(BaseModel):
    """Full input context needed to explain a daily study plan."""

    model_config = ConfigDict(extra="forbid")

    student_name: str = Field(default="Học sinh")
    today_tasks: list[StudyPlanExplanationItem] = Field(default_factory=list)
    academic_goal_title: str | None = None
    target_score: float | None = None
    days_remaining: int | None = None
    recent_progress_summary: str | None = None
    weak_problem_types: list[str] = Field(
        default_factory=list,
        description="Names of problem types where student mastery is below proficiency threshold.",
    )
    relevant_weak_concepts: list[str] = Field(
        default_factory=list,
        description="Names of weak underlying/prerequisite concepts associated with current tasks.",
    )
    teaching_plan_context: str | None = Field(
        default=None,
        description="Current classroom lesson or active topic in school curriculum.",
    )


class StudyPlanExplanationOutput(BaseModel):
    """Strict structured output produced by AI for study plan explanation."""

    model_config = ConfigDict(extra="forbid")

    concise_daily_overview: str = Field(
        ...,
        description="Tổng quan ngắn gọn về kế hoạch học tập hôm nay (1-2 câu súc tích).",
    )
    priority_reasoning: str = Field(
        ...,
        description=(
            "Lý giải vì sao các nhiệm vụ hôm nay được xếp thứ tự ưu tiên như vậy, "
            "kết nối giữa dạng bài chính và kiến thức tiên quyết (ví dụ: hôm nay ưu tiên "
            "dạng tìm tham số về tính đơn điệu vì kết quả gần đây còn yếu; một phần bài tập "
            "cũng củng cố kỹ năng giải bất phương trình). TUYỆT ĐỐI KHÔNG nhắc đến điểm yếu "
            "không có trong danh sách weak_problem_types hoặc relevant_weak_concepts."
        ),
    )
    getting_started_guide: str = Field(
        ...,
        description="Hướng dẫn cụ thể cho học sinh: nên bắt đầu từ nhiệm vụ nào trước và mẹo tiếp cận nhanh hiệu quả.",
    )


class StudyPlanExplanationRead(BaseModel):
    """API response schema presenting the study plan explanation."""

    concise_daily_overview: str
    priority_reasoning: str
    getting_started_guide: str
    is_fallback: bool = Field(
        default=False,
        description="True if explanation was generated by deterministic fallback when AI was unavailable.",
    )
    generated_at: datetime
